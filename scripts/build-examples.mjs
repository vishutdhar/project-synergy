// Writes site/examples.js from tests/variations/items.json: the hand-written Normal to Corporate
// examples that AI mode retrieves as few-shot examples. Run after editing tests/variations/src.
import fs from "node:fs";
const items = JSON.parse(fs.readFileSync(new URL("../tests/variations/items.json", import.meta.url)));
const rows = items.filter((i) => i.direction === "toCorporate" && !i.input.includes("\n")).map((i) => [i.input, ...i.ideal]);
const body = `// Generated by scripts/build-examples.mjs from tests/variations. Do not edit by hand.\n// [input, Mild, Middle Manager, Full C-Suite]\nexport const EXAMPLES = ${JSON.stringify(rows).replace(/\],\[/g, "],\n[")};\n`;
fs.writeFileSync(new URL("../site/examples.js", import.meta.url), body);
console.log(`${rows.length} examples, ${(body.length / 1024).toFixed(0)} KB`);
